//! Friends and friend requests.
//! The contract (`FriendStore`) and its SQLite implementation live together.

use protocol::Id;

use super::queries;
use super::sqlite::SqliteStorage;
use crate::models::*;
use crate::time::now_ms;

#[async_trait::async_trait]
pub trait FriendStore: Send + Sync {
    /// Sends a friend request from `sender_id` to `recipient_id`. If
    /// `recipient_id` already has a pending request in *to* `sender_id`,
    /// this resolves it as a mutual accept (`BecameFriends`) instead of
    /// creating a redundant second pending row.
    async fn send_friend_request(
        &self,
        id: Id,
        sender_id: Id,
        recipient_id: Id,
        created_at: i64,
    ) -> anyhow::Result<SendFriendRequestOutcome>;

    /// Every pending request touching `user_id`, incoming and outgoing.
    async fn list_friend_requests(&self, user_id: Id) -> anyhow::Result<Vec<FriendRequest>>;

    /// Accepts request `request_id` on behalf of `acting_user_id`, who
    /// must be its recipient (anything else — wrong user, or the
    /// request doesn't exist — is `NotFound`, mirroring how a
    /// `restricted` channel 404s rather than 403s for a non-member).
    /// Also creates the DM channel between them (`new_dm_channel_id`,
    /// pre-generated by the caller), same as `get_or_create_dm`.
    async fn accept_friend_request(
        &self,
        request_id: Id,
        acting_user_id: Id,
        new_dm_channel_id: Id,
    ) -> anyhow::Result<AcceptFriendRequestOutcome>;

    /// Declines (as recipient) or cancels (as sender) request
    /// `request_id` on behalf of `acting_user_id` — same operation
    /// either way, just deleting the pending row. `Ok(true)` if a row
    /// was actually removed.
    async fn remove_friend_request(
        &self,
        request_id: Id,
        acting_user_id: Id,
    ) -> anyhow::Result<bool>;

    async fn list_friends(&self, user_id: Id) -> anyhow::Result<Vec<User>>;

    async fn remove_friend(&self, user_id: Id, friend_id: Id) -> anyhow::Result<bool>;

    async fn set_accepts_friend_requests(&self, user_id: Id, accepts: bool) -> anyhow::Result<()>;
}

#[async_trait::async_trait]
impl FriendStore for SqliteStorage {
    async fn send_friend_request(
        &self,
        id: Id,
        sender_id: Id,
        recipient_id: Id,
        created_at: i64,
    ) -> anyhow::Result<SendFriendRequestOutcome> {
        self.with_conn(move |conn| {
            let tx = conn.unchecked_transaction()?;

            if sender_id == recipient_id {
                return Ok(SendFriendRequestOutcome::CannotFriendSelf);
            }
            if queries::friendships::are_friends(&tx, sender_id, recipient_id)? {
                return Ok(SendFriendRequestOutcome::AlreadyFriends);
            }
            if !queries::users::by_id(&tx, recipient_id)?
                .ok_or(rusqlite::Error::QueryReturnedNoRows)?
                .accepts_friend_requests
            {
                return Ok(SendFriendRequestOutcome::NotAcceptingRequests);
            }

            // The other person already invited *you* — resolve as a
            // mutual accept instead of a second, redundant pending row.
            if let Some(existing) = queries::friend_requests::between(&tx, sender_id, recipient_id)?
            {
                if existing.sender_id == recipient_id {
                    queries::friendships::add(&tx, sender_id, recipient_id, created_at)?;
                    queries::friend_requests::delete(&tx, existing.id)?;
                    let friend = queries::users::by_id(&tx, recipient_id)?
                        .ok_or(rusqlite::Error::QueryReturnedNoRows)?;
                    tx.commit()?;
                    return Ok(SendFriendRequestOutcome::BecameFriends(friend));
                }
                return Ok(SendFriendRequestOutcome::AlreadyRequested);
            }

            queries::friend_requests::create(&tx, sender_id, recipient_id, id, created_at)?;
            let other = queries::users::by_id(&tx, recipient_id)?
                .ok_or(rusqlite::Error::QueryReturnedNoRows)?;
            tx.commit()?;
            Ok(SendFriendRequestOutcome::Requested(FriendRequest {
                id,
                other,
                created_at,
                incoming: false,
            }))
        })
        .await
    }

    async fn list_friend_requests(&self, user_id: Id) -> anyhow::Result<Vec<FriendRequest>> {
        self.with_conn(move |conn| queries::friend_requests::list_for_user(conn, user_id)).await
    }

    async fn accept_friend_request(
        &self,
        request_id: Id,
        acting_user_id: Id,
        new_dm_channel_id: Id,
    ) -> anyhow::Result<AcceptFriendRequestOutcome> {
        self.with_conn(move |conn| {
            let tx = conn.unchecked_transaction()?;

            let Some(req) = queries::friend_requests::by_id(&tx, request_id)? else {
                return Ok(AcceptFriendRequestOutcome::NotFound);
            };
            if req.recipient_id != acting_user_id {
                return Ok(AcceptFriendRequestOutcome::NotFound);
            }

            queries::friendships::add(&tx, req.sender_id, req.recipient_id, now_ms())?;
            queries::friend_requests::delete(&tx, request_id)?;
            if queries::dms::find_existing(&tx, req.sender_id, req.recipient_id)?.is_none() {
                queries::dms::create(&tx, new_dm_channel_id, req.sender_id, req.recipient_id)?;
            }
            let friend = queries::users::by_id(&tx, req.sender_id)?
                .ok_or(rusqlite::Error::QueryReturnedNoRows)?;
            tx.commit()?;
            Ok(AcceptFriendRequestOutcome::Ok(friend))
        })
        .await
    }

    async fn remove_friend_request(
        &self,
        request_id: Id,
        acting_user_id: Id,
    ) -> anyhow::Result<bool> {
        self.with_conn(move |conn| {
            let Some(req) = queries::friend_requests::by_id(conn, request_id)? else {
                return Ok(false);
            };
            if req.sender_id != acting_user_id && req.recipient_id != acting_user_id {
                return Ok(false);
            }
            queries::friend_requests::delete(conn, request_id)?;
            Ok(true)
        })
        .await
    }

    async fn list_friends(&self, user_id: Id) -> anyhow::Result<Vec<User>> {
        self.with_conn(move |conn| queries::friendships::list_for_user(conn, user_id)).await
    }

    async fn remove_friend(&self, user_id: Id, friend_id: Id) -> anyhow::Result<bool> {
        self.with_conn(move |conn| queries::friendships::remove(conn, user_id, friend_id)).await
    }

    async fn set_accepts_friend_requests(&self, user_id: Id, accepts: bool) -> anyhow::Result<()> {
        self.with_conn(move |conn| {
            queries::users::set_accepts_friend_requests(conn, user_id, accepts)
        })
        .await
    }
}
